// scripts/ingest-docs.mjs — offline ingestion for the L2 RAG corpus.
//
// Reads docs/*.md, docs/decisions/*.md and selected docs/ops/*.md, splits each
// file into section-level chunks (## headings), and emits SQL INSERT statements
// for the rag_docs table (migrations/0012_rag_docs.sql).
//
// Usage:
//   node scripts/ingest-docs.mjs > scripts/rag-seed.sql
//   wrangler d1 execute trading_dev --file=scripts/rag-seed.sql --local
//   # or --remote for production
//
// Idempotent: each chunk id = "<path>#<section>"; re-running replaces same-id rows.

import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { createHash } from "node:crypto";

const ROOT = process.cwd();
const DOCS_DIRS = [
  join(ROOT, "docs"),
  join(ROOT, "docs", "decisions"),
  join(ROOT, "docs", "ops"),
];
// Ops files that are genuinely reference material for the model (skip drill evidence etc.)
const OPS_ALLOWLIST = [
  "TOOBIT-API-FACTS.md",
  "RBAC-MATRIX.md",
  "CONFIG-MATRIX.md",
  "SECRET-STORE.md",
  "GIT-DEPLOYS.md",
];

function mdFiles(dir) {
  try {
    return readdirSync(dir)
      .filter((f) => f.endsWith(".md"))
      .map((f) => join(dir, f))
      .sort();
  } catch { return []; }
}

const files = DOCS_DIRS.flatMap((d) =>
  mdFiles(d).filter((f) => {
    if (d.endsWith("ops")) return OPS_ALLOWLIST.includes(f.split("/").pop());
    return true;
  })
);

function sha256(text) {
  return createHash("sha256").update(text).digest("hex");
}

/** Escape a string for a SQL single-quoted literal. */
function sqlLit(s) {
  return "'" + String(s ?? "").replace(/'/g, "''") + "'";
}

/** Split markdown into section chunks by `## ` headings. */
function chunkBySection(path, text) {
  const title = path.split("/").pop().replace(/\.md$/, "");
  const lines = text.split("\n");
  const chunks = [];
  let currentSection = null;
  let currentBuf = [];

  const flush = () => {
    if (currentBuf.join("\n").trim()) {
      chunks.push({
        section: currentSection ?? "(overview)",
        content: currentBuf.join("\n").trim(),
      });
    }
    currentBuf = [];
  };

  for (const line of lines) {
    const m = line.match(/^##\s+(.+)$/);
    if (m) {
      flush();
      currentSection = m[1].trim();
    } else {
      currentBuf.push(line);
    }
  }
  flush();

  if (!chunks.length) {
    chunks.push({ section: "(overview)", content: text.trim() });
  }

  return chunks.map((c, i) => ({
    id: `${path}#${i}`,
    path,
    title,
    section: c.section,
    content: c.content,
    chunk_idx: i,
    content_hash: sha256(c.content),
    updated_at: new Date().toISOString(),
  }));
}

const sql = [];
sql.push("-- rag seed — generated by scripts/ingest-docs.mjs");
sql.push("-- Apply: wrangler d1 execute <db> --file=scripts/rag-seed.sql");
sql.push("");

for (const f of files) {
  const text = readFileSync(f, "utf8");
  const path = f.replace(ROOT + "/", "");
  const chunks = chunkBySection(path, text);
  for (const c of chunks) {
    sql.push(
      `INSERT OR REPLACE INTO rag_docs(id, path, title, section, content, chunk_idx, content_hash, updated_at) VALUES(${sqlLit(c.id)}, ${sqlLit(c.path)}, ${sqlLit(c.title)}, ${sqlLit(c.section)}, ${sqlLit(c.content)}, ${c.chunk_idx}, ${sqlLit(c.content_hash)}, ${sqlLit(c.updated_at)});`
    );
  }
}

process.stdout.write(sql.join("\n") + "\n");
