#!/usr/bin/env node
// strategy-new.mjs — scaffold a NEW strategy module the contract can accept.
//
// WHY IT EXISTS: docs/19 §19.6 step 1 is "copy go-watcher/strategies/template/
// to a standalone dir (own go.mod, stdlib-only)". Done by hand that step is
// where people accidentally import the watcher, forget go.mod, or edit the
// envelope the Worker's prompt depends on. This script does it exactly right,
// and — because it copies the WORKING template — the new module already passes
// `strategy-check` before the author writes a line of logic.
//
// usage: node scripts/strategy-new.mjs --id rsi-reversion [--name "..."] [--dir strategies/dev]
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const TEMPLATE = join(ROOT, "go-watcher", "strategies", "template");
const ID_RE = /^[a-z0-9][a-z0-9-_]{1,63}$/;

function fail(msg) {
  console.error(`strategy-new: ${msg}`);
  process.exit(1);
}

function parseArgs(argv) {
  const out = { dir: "strategies/dev", version: "0.1.0" };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--id") out.id = argv[++i];
    else if (a === "--name") out.name = argv[++i];
    else if (a === "--dir") out.dir = argv[++i];
    else if (a === "--version") out.version = argv[++i];
    else if (a === "--help" || a === "-h") out.help = true;
    else fail(`unknown argument ${a}`);
  }
  return out;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  if (args.help) {
    console.log("usage: node scripts/strategy-new.mjs --id <id> [--name \"Human Name\"] [--dir strategies/dev] [--version 0.1.0]");
    return;
  }
  if (!args.id) fail("--id is required");
  if (!ID_RE.test(args.id)) fail(`id "${args.id}" must match ${ID_RE} (lowercase, digits, - and _, 2-64 chars)`);
  if (!/^\d+\.\d+\.\d+$/.test(args.version)) fail(`--version "${args.version}" must be x.y.z`);

  const targetRel = join(args.dir, args.id);
  const target = resolve(ROOT, targetRel);
  // Fail closed: re-scaffolding over an existing module would silently discard
  // whatever the author already wrote.
  if (existsSync(target)) fail(`${targetRel} already exists — refusing to overwrite`);

  const srcMain = join(TEMPLATE, "main.go");
  if (!existsSync(srcMain)) fail(`${srcMain} not found — is this the repo root?`);
  const templateSrc = readFileSync(srcMain, "utf8");

  // The banner goes BEFORE `package main` and changes nothing else, so the
  // envelope (types, main(), helpers) stays byte-identical to the template the
  // Worker's prompt and the drift test depend on.
  const banner = [
    `// SCAFFOLD ${args.id}@${args.version} — generated by scripts/strategy-new.mjs.`,
    "//",
    "// Edit ONLY the decide() function (plus unexported helpers it needs). Keep",
    "// everything below the \"DO NOT EDIT\" marker byte-identical: the runner, the",
    "// golden fixtures and the chat prompt all assume that envelope.",
    "//",
    "// The copied logic is the sma-cross reference, so this module already passes",
    "//   node scripts/strategy-pipeline.mjs --src " + targetRel + " --id " + args.id + " --version " + args.version,
    "// Replace it with your rule, re-run the pipeline, and only then register.",
    "",
  ].join("\n");
  const mainGo = banner + templateSrc;

  mkdirSync(target, { recursive: true });
  writeFileSync(join(target, "main.go"), mainGo);
  // go.mod pins the SAME language version as go-watcher and CI: a toolchain gap
  // is how a "reproducible" artifact silently stops being reproducible.
  writeFileSync(join(target, "go.mod"), "module strategy\n\ngo 1.25.0\n");
  writeFileSync(join(target, "strategy.json"), JSON.stringify({
    id: args.id,
    version: args.version,
    name: args.name || args.id,
    description: "",
    configuration: {},
  }, null, 2) + "\n");

  console.log(`scaffolded ${targetRel}`);
  console.log(`  main.go        — edit decide(), keep the envelope`);
  console.log(`  go.mod         — module strategy, go 1.25.0 (standalone, stdlib only)`);
  console.log(`  strategy.json  — catalog metadata for the registry row`);
  console.log("\nnext:");
  console.log(`  node scripts/strategy-pipeline.mjs --src ${targetRel} --id ${args.id} --version ${args.version}`);
}

main();
